import { LlmConfigError } from '@ghostiq/llm';
import { describe, expect, it } from 'vitest';
import type { PrismaClient } from './db.js';
import { loadEnv } from './env.js';
import { createLlmRuntime, resolveLlmConfig } from './llm.js';
import { renderDiagnostics } from './services/ai.js';

const env = (vars: Record<string, string>) => loadEnv({ NODE_ENV: 'test', ...vars });

describe('resolveLlmConfig', () => {
  it('falls back to labelled demo mode when nothing is configured', () => {
    const { config, demoReason } = resolveLlmConfig(env({}));
    expect(config.primary.provider).toBe('mock');
    expect(demoReason).toMatch(/no API key/i);
  });

  it('treats empty strings (docker compose) as unset', () => {
    const { config } = resolveLlmConfig(
      env({ GHOSTIQ_LLM_PROVIDER: '', GHOSTIQ_LLM_API_KEY: '  ' }),
    );
    expect(config.primary.provider).toBe('mock');
  });

  it('picks Gemini when only a Gemini key is present', () => {
    const { config, demoReason } = resolveLlmConfig(env({ GEMINI_API_KEY: 'g-key' }));
    expect(config.primary.provider).toBe('gemini');
    expect(config.providerKeys.gemini).toBe('g-key');
    expect(demoReason).toBeUndefined();
  });

  it('honours an explicit provider, model, fallbacks and price override', () => {
    const { config } = resolveLlmConfig(
      env({
        GHOSTIQ_LLM_PROVIDER: 'claude',
        GHOSTIQ_LLM_MODEL: 'claude-sonnet-5-5',
        GHOSTIQ_LLM_FALLBACK: 'ollama:llama3.2,mock',
        GHOSTIQ_LLM_PRICE_INPUT: '1',
        GHOSTIQ_LLM_PRICE_OUTPUT: '2',
      }),
    );
    expect(config.primary).toMatchObject({ provider: 'claude', model: 'claude-sonnet-5-5' });
    expect(config.fallbacks).toEqual([
      { provider: 'ollama', model: 'llama3.2' },
      { provider: 'mock' },
    ]);
    expect(config.price).toEqual({ input: 1, output: 2 });
  });

  it('fails loudly at boot when an explicit provider is misconfigured', () => {
    const fakePrisma = {} as PrismaClient;
    expect(() => createLlmRuntime(env({ GHOSTIQ_LLM_PROVIDER: 'gemini' }), fakePrisma)).toThrow(
      LlmConfigError,
    );
  });
});

describe('renderDiagnostics', () => {
  it('labels the report as AI-generated with its confidence', () => {
    const md = renderDiagnostics(
      {
        summary: 'Login fails.',
        rootCause: 'POST /api/auth/login returns 500.',
        failedStep: 4,
        evidence: ['500 on /api/auth/login'],
        recommendedFixes: ['Check the auth service'],
        confidence: 'medium',
      },
      'gemini/gemini-3.5-flash-lite',
    );
    expect(md).toContain('AI-generated by gemini/gemini-3.5-flash-lite');
    expect(md).toContain('confidence: **medium**');
    expect(md).toContain('(step 4)');
    expect(md).toContain('1. Check the auth service');
  });
});
